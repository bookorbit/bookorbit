#!/usr/bin/env bash
# Writes the translation template (bookorbit.pot) from the plugin's source.
# Usage: extract.sh [output]   Default output: bookorbit.pot next to this script.
# The creation date only moves when the strings change, so an unchanged
# template never shows up in a diff.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
plugin="$here/../bookorbit.koplugin"
out="${1:-$here/bookorbit.pot}"

if ! command -v xgettext >/dev/null 2>&1; then
    echo "xgettext not found: install GNU gettext (brew install gettext, apt install gettext)" >&2
    exit 1
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(
    cd "$plugin"
    LC_ALL=C find . -name '*.lua' -type f | sed 's|^\./||' | LC_ALL=C sort >"$work/files"
    xgettext --from-code=UTF-8 --language=Lua \
        --keyword=_ --keyword=_.ngettext:1,2 --keyword=_.pgettext:1c,2 --keyword=_.npgettext:1c,2,3 \
        --add-comments=TRANSLATORS: --add-location=file --sort-by-file --no-wrap \
        --files-from="$work/files" --output="$work/raw.pot"
)

# Everything after xgettext's header entry.
body() { awk 'found { print } /^$/ && !found { found = 1 }' "$1"; }
body "$work/raw.pot" >"$work/body"

date="$(TZ=UTC date '+%Y-%m-%d %H:%M+0000')"
if [ -f "$out" ] && body "$out" | cmp -s - "$work/body"; then
    kept="$(sed -n 's/^"POT-Creation-Date: \(.*\)\\n"$/\1/p' "$out")"
    date="${kept:-$date}"
fi

{
    echo '# Translation template for the BookOrbit KOReader plugin.'
    echo '# Generated by koreader-plugin/l10n/extract.sh; do not edit by hand.'
    echo '# Translator guide: koreader-plugin/l10n/README.md'
    echo 'msgid ""'
    echo 'msgstr ""'
    echo '"Project-Id-Version: bookorbit.koplugin\n"'
    echo '"Report-Msgid-Bugs-To: https://github.com/bookorbit/bookorbit/issues\n"'
    echo "\"POT-Creation-Date: $date\\n\""
    echo '"Language: \n"'
    echo '"MIME-Version: 1.0\n"'
    echo '"Content-Type: text/plain; charset=UTF-8\n"'
    echo '"Content-Transfer-Encoding: 8bit\n"'
    echo
    cat "$work/body"
} >"$work/out.pot"

mv "$work/out.pot" "$out"
echo "$(($(grep -c '^msgid ' "$out") - 1)) strings in ${out#"$PWD/"}"
